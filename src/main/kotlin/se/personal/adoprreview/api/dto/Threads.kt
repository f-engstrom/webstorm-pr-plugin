package se.personal.adoprreview.api.dto

import kotlinx.serialization.Serializable
import kotlinx.serialization.Transient
import kotlinx.serialization.json.JsonObject
import java.time.Instant

@Serializable
data class CommentThread(
    val id: Int,
    val status: String? = null,
    val threadContext: ThreadContext? = null,
    val pullRequestThreadContext: PrThreadContext? = null,
    val comments: List<Comment> = emptyList(),
    val properties: JsonObject? = null,
    val isDeleted: Boolean = false,
    val publishedDate: String? = null,
    val lastUpdatedDate: String? = null,
) {
    /** Threads generated by ADO itself, e.g. "pushed new commits" or vote changes. */
    val isSystem: Boolean
        get() = properties?.containsKey("CodeReviewThreadType") == true ||
            (threadContext == null && comments.all { it.commentType == "system" })

    val visibleComments: List<Comment> get() = comments.filter { !it.isDeleted && it.commentType != "system" }

    val filePath: String? get() = threadContext?.filePath

    val threadStatus: ThreadStatus get() = ThreadStatus.of(status)
}

@Serializable
data class ThreadContext(
    val filePath: String? = null,
    /** Source (new) side, 1-based. */
    val rightFileStart: FilePosition? = null,
    val rightFileEnd: FilePosition? = null,
    /** Target (old) side, 1-based. */
    val leftFileStart: FilePosition? = null,
    val leftFileEnd: FilePosition? = null,
)

@Serializable
data class FilePosition(val line: Int, val offset: Int = 1)

@Serializable
data class PrThreadContext(val changeTrackingId: Int? = null, val iterationContext: IterationContext? = null)

@Serializable
data class IterationContext(val firstComparingIteration: Int, val secondComparingIteration: Int)

@Serializable
data class Comment(
    val id: Int,
    val parentCommentId: Int = 0,
    val author: IdentityRef = IdentityRef(),
    /** Markdown, with `@<GUID>` mentions replaced by names for display (see [rawContent]). */
    val content: String? = null,
    val publishedDate: String? = null,
    val lastUpdatedDate: String? = null,
    /** Changes only when the text was edited (unlike [lastUpdatedDate], which likes also touch). */
    val lastContentUpdatedDate: String? = null,
    val commentType: String? = null,
    val isDeleted: Boolean = false,
    val usersLiked: List<IdentityRef> = emptyList(),
    /** The content as stored, with real mentions; what editing starts from. Not part of the JSON. */
    @Transient val rawContent: String? = null,
) {
    fun isBy(userId: String): Boolean = author.id.equals(userId, ignoreCase = true)

    fun isLikedBy(userId: String): Boolean = usersLiked.any { it.id.equals(userId, ignoreCase = true) }

    /** Edited after posting; a second of slack because ADO stores the two dates separately. */
    val isEdited: Boolean
        get() {
            val published = publishedDate?.let { runCatching { Instant.parse(it) }.getOrNull() } ?: return false
            val edited = lastContentUpdatedDate?.let { runCatching { Instant.parse(it) }.getOrNull() } ?: return false
            return edited.isAfter(published.plusSeconds(1))
        }
}

@Serializable
data class CommentUpdate(val content: String)

enum class ThreadStatus(val value: String, val label: String, val isResolved: Boolean) {
    ACTIVE("active", "Active", false),
    PENDING("pending", "Pending", false),
    FIXED("fixed", "Resolved", true),
    WONT_FIX("wontFix", "Won't fix", true),
    CLOSED("closed", "Closed", true),
    BY_DESIGN("byDesign", "By design", true),
    UNKNOWN("unknown", "Unknown", false);

    companion object {
        fun of(value: String?): ThreadStatus = entries.firstOrNull { it.value.equals(value, ignoreCase = true) } ?: UNKNOWN
    }
}

@Serializable
data class NewComment(val content: String, val parentCommentId: Int, val commentType: Int)

@Serializable
data class ThreadStatusUpdate(val status: String)

/** Body of `POST .../threads`. The iteration context and change tracking ID keep the thread anchored after new pushes. */
@Serializable
data class NewThread(
    val comments: List<NewComment>,
    val status: String,
    val threadContext: ThreadContext? = null,
    val pullRequestThreadContext: PrThreadContext? = null,
)

/** Filters out system and deleted threads, keeping only ones with something to show. */
fun List<CommentThread>.reviewThreads(): List<CommentThread> =
    filter { !it.isDeleted && !it.isSystem && it.visibleComments.isNotEmpty() }
